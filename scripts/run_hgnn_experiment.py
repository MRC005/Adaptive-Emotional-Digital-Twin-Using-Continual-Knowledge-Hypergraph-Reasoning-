#!/usr/bin/env python3
"""HGNN vs baselines on emotional-event prediction.

TASK
----
Given the non-emotion context of an episode (event category, sleep, workload,
social, activity, location, time), predict the emotion recorded for it. This is
edge-level classification over the event hypergraph.

PROTOCOL
--------
data      A synthetic multi-person cohort, generated by
          ``aedt/simulate/event_cohort.py`` with a KNOWN context->emotion rule
          plus label noise. Real check-in data at this scale does not exist for
          this project, and saying so is better than borrowing a corpus that
          measures something else.
split     Edges split 60/20/20 train/val/test, stratified by emotion, seed
          20260828. The split is over EDGES; the hypergraph structure is shared,
          which is the standard transductive setting for this model class.
leakage   Emotion vertices are REMOVED from the incidence matrix before any
          model sees it (``mask_emotion_vertices``). Without this every model
          scores ~1.0 because the answer is an input.
models    HGNN (Feng et al. hypergraph convolution)
          GCN  (same budget, clique expansion -- pairwise control)
          MLP  (no structure at all -- floor)
          Majority (predicts the commonest class -- sanity floor)
training  Adam 1e-2, weight decay 5e-4, 300 epochs, early stop on val macro-F1
          with patience 40. Identical for every neural model.
metrics   accuracy, macro-F1, weighted-F1 on the test edges. Macro-F1 leads
          because the emotion classes are imbalanced.
repeats   5 seeds; mean and standard deviation reported.

    python3 scripts/run_hgnn_experiment.py [--seeds 5] [--epochs 300]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

SEED = 20260828
OUT = ROOT / "results" / "hgnn"


def split_edges(y, seed, frac=(0.6, 0.2, 0.2)):
    """Stratified edge split. Classes with too few members go to train."""
    rng = np.random.default_rng(seed)
    tr, va, te = [], [], []
    for c in np.unique(y):
        idx = np.where(y == c)[0]
        rng.shuffle(idx)
        if len(idx) < 5:
            tr.extend(idx)
            continue
        n_tr = int(round(frac[0] * len(idx)))
        n_va = int(round(frac[1] * len(idx)))
        tr.extend(idx[:n_tr]); va.extend(idx[n_tr:n_tr + n_va]); te.extend(idx[n_tr + n_va:])
    return np.array(sorted(tr)), np.array(sorted(va)), np.array(sorted(te))


def train_eval(kind, X, H, y, splits, *, seed, epochs, hidden=32, lr=1e-2, wd=5e-4):
    import torch
    import torch.nn.functional as F
    from sklearn.metrics import accuracy_score, f1_score
    from aedt.models.hgnn import GCNBaseline, HGNN, MLPBaseline

    torch.manual_seed(seed)
    tr, va, te = splits
    Xt = torch.tensor(X, dtype=torch.float32)
    Ht = torch.tensor(H, dtype=torch.float32)
    yt = torch.tensor(y, dtype=torch.long)
    n_classes = int(y.max()) + 1

    if kind == "hgnn":
        model = HGNN(X.shape[1], hidden, n_classes, H.shape[1])
    elif kind == "gcn":
        model = GCNBaseline(X.shape[1], hidden, n_classes)
    elif kind == "mlp":
        model = MLPBaseline(X.shape[1], hidden, n_classes)
    else:
        raise ValueError(kind)

    opt = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=wd)
    best_val, best_state, patience = -1.0, None, 0
    for ep in range(epochs):
        model.train(); opt.zero_grad()
        out = model(Xt, Ht)
        loss = F.cross_entropy(out[tr], yt[tr])
        loss.backward(); opt.step()

        model.eval()
        with torch.no_grad():
            pred = model(Xt, Ht).argmax(dim=1).numpy()
        vf1 = f1_score(y[va], pred[va], average="macro", zero_division=0)
        if vf1 > best_val:
            best_val, patience = vf1, 0
            best_state = {k: v.clone() for k, v in model.state_dict().items()}
        else:
            patience += 1
            if patience >= 40:
                break
    if best_state:
        model.load_state_dict(best_state)
    model.eval()
    with torch.no_grad():
        pred = model(Xt, Ht).argmax(dim=1).numpy()
    return {
        "accuracy": float(accuracy_score(y[te], pred[te])),
        "macro_f1": float(f1_score(y[te], pred[te], average="macro", zero_division=0)),
        "weighted_f1": float(f1_score(y[te], pred[te], average="weighted", zero_division=0)),
    }


def majority(y, splits):
    from sklearn.metrics import accuracy_score, f1_score
    tr, _, te = splits
    c = np.bincount(y[tr]).argmax()
    pred = np.full(len(te), c)
    return {
        "accuracy": float(accuracy_score(y[te], pred)),
        "macro_f1": float(f1_score(y[te], pred, average="macro", zero_division=0)),
        "weighted_f1": float(f1_score(y[te], pred, average="weighted", zero_division=0)),
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--epochs", type=int, default=300)
    ap.add_argument("--people", type=int, default=60)
    ap.add_argument("--events", type=int, default=40)
    args = ap.parse_args()

    from aedt.models.hgnn import build_tensors, torch_available
    if not torch_available():
        print("NOT RUN: torch is not installed. This experiment is a research "
              "component and requires it; nothing is estimated without it.")
        return 2

    from aedt.simulate.event_cohort import build_cohort_hypergraph

    rows = []
    for i in range(args.seeds):
        seed = SEED + i
        graph, truth = build_cohort_hypergraph(
            n_people=args.people, n_events=args.events, seed=seed)
        X, H, y, meta = build_tensors(graph)
        keep = y >= 0
        if not keep.all():                     # edges with no emotion vertex
            H = H[:, keep]; y = y[keep]
        splits = split_edges(y, seed)
        print(f"seed {seed}: {H.shape[0]} vertices, {H.shape[1]} edges, "
              f"{len(meta['classes'])} classes, "
              f"split {len(splits[0])}/{len(splits[1])}/{len(splits[2])}", flush=True)

        r = {"seed": seed, "majority": majority(y, splits)}
        for kind in ("mlp", "gcn", "hgnn"):
            r[kind] = train_eval(kind, X, H, y, splits, seed=seed, epochs=args.epochs)
            print(f"    {kind:4s} macro-F1 {r[kind]['macro_f1']:.4f} "
                  f"acc {r[kind]['accuracy']:.4f}", flush=True)
        rows.append(r)

    def agg(kind, metric):
        v = [r[kind][metric] for r in rows]
        return float(np.mean(v)), float(np.std(v))

    summary = {}
    for kind in ("majority", "mlp", "gcn", "hgnn"):
        summary[kind] = {m: {"mean": agg(kind, m)[0], "std": agg(kind, m)[1]}
                         for m in ("accuracy", "macro_f1", "weighted_f1")}

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "hgnn_experiment.json").write_text(json.dumps(
        {"protocol": {
            "task": "edge-level emotion classification on the event hypergraph",
            "data": "SYNTHETIC cohort with a known context->emotion rule plus noise",
            "n_people": args.people, "n_events_per_person": args.events,
            "split": "60/20/20 stratified over edges", "seed": SEED,
            "seeds": args.seeds, "epochs": args.epochs,
            "emotion_vertices_masked": True,
            "note": "Real check-in data at this scale does not exist for this "
                    "project; the comparison is between models on identical "
                    "synthetic data, not a claim about human data."},
         "runs": rows, "summary": summary}, indent=2))

    print("\n================ HGNN EXPERIMENT (mean +/- sd over "
          f"{args.seeds} seeds) ================")
    print(f"{'model':10s} {'accuracy':>16s} {'macro-F1':>16s} {'weighted-F1':>16s}")
    for kind in ("majority", "mlp", "gcn", "hgnn"):
        s = summary[kind]
        print(f"{kind:10s} "
              f"{s['accuracy']['mean']:.4f}+/-{s['accuracy']['std']:.3f}  "
              f"{s['macro_f1']['mean']:.4f}+/-{s['macro_f1']['std']:.3f}  "
              f"{s['weighted_f1']['mean']:.4f}+/-{s['weighted_f1']['std']:.3f}")
    d = summary["hgnn"]["macro_f1"]["mean"] - summary["gcn"]["macro_f1"]["mean"]
    print(f"\nHGNN minus GCN on macro-F1: {d:+.4f}")
    print("A negative or near-zero value means the higher-order structure did "
          "NOT earn its place on this data, and is reported as such.")
    print(f"\nwritten: {OUT / 'hgnn_experiment.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
